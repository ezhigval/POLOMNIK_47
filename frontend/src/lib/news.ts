export function formatNewsDate(isoDate: string): string {
  const date = new Date(`${isoDate.slice(0, 10)}T12:00:00`);
  return new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(date);
}

export function paragraphsFromBody(body: string): string[] {
  return body
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean);
}

export function toFeedArticle(article: {
  slug: string;
  title: string;
  excerpt: string;
  body: string;
  image_url: string;
  published_at: string;
}): NewsArticle {
  return {
    slug: article.slug,
    title: article.title,
    date: article.published_at.slice(0, 10),
    excerpt: article.excerpt,
    image: article.image_url,
    paragraphs: paragraphsFromBody(article.body),
  };
}
