const InitialVersion = "1.0"

type DocumentSpec struct {
	Type    domain.LegalDocumentType
	Version string
	Title   string
	Content string
}

// AllInitial returns v1.0 drafts of all legal documents for bootstrap.
func AllInitial(op operator.Config) []DocumentSpec {
	return []DocumentSpec{
		{Type: domain.LegalDocTypePrivacyPolicy, Version: InitialVersion, Title: "Политика в отношении обработки персональных данных", Content: privacyPolicy(op)},
		{Type: domain.LegalDocTypePersonalData, Version: InitialVersion, Title: "Согласие на обработку персональных данных", Content: personalDataConsent(op)},
		{Type: domain.LegalDocTypeDistribution, Version: InitialVersion, Title: "Согласие на обработку персональных данных, разрешённых для распространения", Content: distributionConsent(op)},
		{Type: domain.LegalDocTypeMarketing, Version: InitialVersion, Title: "Согласие на получение рекламных и информационно-маркетинговых сообщений", Content: marketingConsent(op)},
		{Type: domain.LegalDocTypeCookie, Version: InitialVersion, Title: "Политика использования cookie и аналогичных технологий", Content: cookiePolicy(op)},
	}
}

func dash(v string) string {
	if strings.TrimSpace(v) == "" {
		return "—"
	}
	return v
}

func regionsList(regions []string) string {
	return strings.Join(regions, "; ")
}

